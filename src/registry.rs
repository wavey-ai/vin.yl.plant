//! The curated manufacturer and template registry.
//!
//! This is the source of truth for plant geometry. It lives in Rust so a
//! bad measurement is a compile error rather than a runtime surprise, and
//! so every consumer — the web UI and the Apple app both link this crate —
//! reads exactly the same templates.
//!
//! Each entry records where its measurements came from and how confident
//! they are. Anything not `PlantPublished` must be confirmed with the plant
//! before a fully automated plant-ready submission.

